"""Contrato del repositorio. No depende de SQLAlchemy ni de FastAPI."""

from typing import Any, Protocol, List, Optional
from uuid import UUID


class LegajoRepository(Protocol):
    async def obtener_cohorte(self, cohorte_id: UUID) -> Any | None: ...
    async def existe_dni_en_cohorte(self, cohorte_id: UUID, dni: str) -> bool: ...
    async def crear(self, datos: dict[str, Any]) -> Any: ...
    async def listar(self, *, offset: int, limit: int, filtros: dict[str, Any]) -> tuple[list[Any], int]: ...
    async def obtener_por_id(self, legajo_id: UUID) -> Any | None: ...
    async def contar_numeros_legajo(self, cohorte_id: UUID) -> int: ...
    async def agregar_auditoria(self, *, legajo_id: UUID, estado_anterior: str | None,
                                estado_nuevo: str, comentario: str | None,
                                usuario_email: str | None) -> None: ...
    async def guardar(self, legajo: Any) -> Any: ...

class CohorteRepository(Protocol):
    async def obtener(self) -> List[Any]: ...
    async def obtener_por_id(self, cohorte_id: UUID) -> Any | None: ...
    async def crear(self, datos: dict[str, Any]) -> Any: ...
    async def modificar(self, cohorte: Any) -> Any: ...